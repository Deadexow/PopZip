inline void FillTranslucent(HDC dc, const RECT& rc, COLORREF color, BYTE alpha) {
    HDC source = CreateCompatibleDC(dc);
    BITMAPINFO info{};
    info.bmiHeader.biSize = sizeof(BITMAPINFOHEADER);
    info.bmiHeader.biWidth = 1;
    info.bmiHeader.biHeight = 1;
    info.bmiHeader.biPlanes = 1;
    info.bmiHeader.biBitCount = 32;
    info.bmiHeader.biCompression = BI_RGB;
    void* bits = nullptr;
    HBITMAP bitmap =
        CreateDIBSection(dc, &info, DIB_RGB_COLORS, &bits, nullptr, 0);
    if (bitmap == nullptr) {
        DeleteDC(source);
        return;
    }
    HGDIOBJ oldBitmap = SelectObject(source, bitmap);
    BYTE* pixel = static_cast<BYTE*>(bits);
    pixel[0] = GetBValue(color);
    pixel[1] = GetGValue(color);
    pixel[2] = GetRValue(color);
    pixel[3] = 255;
    BLENDFUNCTION blend{};
    blend.BlendOp = AC_SRC_OVER;
    blend.SourceConstantAlpha = alpha;
    blend.AlphaFormat = 0;
    AlphaBlend(dc, rc.left, rc.top, rc.right - rc.left, rc.bottom - rc.top,
               source, 0, 0, 1, 1, blend);
    SelectObject(source, oldBitmap);
    DeleteObject(bitmap);
    DeleteDC(source);
}

inline void FillTranslucentRounded(HDC dc, const RECT& rc, int radius,
                                   COLORREF color, BYTE alpha) {
    HRGN region = CreateRoundRectRgn(rc.left, rc.top, rc.right + 1,
                                     rc.bottom + 1, radius, radius);
    SelectClipRgn(dc, region);
    FillTranslucent(dc, rc, color, alpha);
    SelectClipRgn(dc, nullptr);
    DeleteObject(region);
}